# 19. 行番号ステガノグラフィ
#
# このファイルでは「何行目か」がデータそのものだ。
# 文字コード c の文字は、ちょうど c 行目でわざと IndexError を起こす関数として埋め込んである。
#    32 行目 -> 空白     100 行目 -> d     101 行目 -> e     104 行目 -> h
#   108 行目 -> l        111 行目 -> o     114 行目 -> r     119 行目 -> w
# 例外のトレースバック (tb_next で繋がった鎖) を末端まで辿り、tb_lineno を読むと
# それが文字コードになる。
#
# ※ 1 行でも足したり消したりすると壊れる。左端の目盛りは行番号。


def where(site):
    try:
        site()
    except IndexError as oops:
        trace = oops.__traceback__
        while trace.tb_next:
            trace = trace.tb_next
        return trace.tb_lineno

